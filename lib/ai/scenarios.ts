/**
 * Build the full system prompt: base + scenario persona + dynamic user context.
 */
export function buildSystemPrompt(
  scenario: AIScenario,
  context: {
    userName?: string | null;
    communityName?: string | null;
    role?: string | null;
    parsha?: string | null;
    todayHebrew?: string | null;
    timezone?: string | null;
  },
): string {
  const meta = SCENARIOS[scenario];
  const ctxLines: string[] = [];
  if (context.userName) ctxLines.push(`Имя пользователя: ${context.userName}`);
  if (context.communityName) ctxLines.push(`Община: ${context.communityName}`);
  if (context.role) ctxLines.push(`Роль в общине: ${context.role}`);
  if (context.parsha) ctxLines.push(`Парша этой недели: ${context.parsha}`);
  if (context.todayHebrew) ctxLines.push(`Сегодня по еврейскому календарю: ${context.todayHebrew}`);
  if (context.timezone) ctxLines.push(`Часовой пояс пользователя: ${context.timezone}`);

  const ctxBlock = ctxLines.length
    ? `\n\n=== Контекст пользователя ===\n${ctxLines.join('\n')}`
    : '';

  return `${BASE_SYSTEM_PROMPT}\n\n=== Текущий сценарий ===\n${meta.systemPersona}${ctxBlock}`;
}

