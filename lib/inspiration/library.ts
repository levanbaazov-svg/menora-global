export function getItemBySlug(slug: string): InspirationItem | null {
  return INSPIRATION_LIBRARY.find((i) => i.slug === slug) ?? null;
}

export function getItemsByKind(kind: ItemKind): InspirationItem[] {
  return INSPIRATION_LIBRARY.filter((i) => i.kind === kind);
}

/**
 * Pick today's featured item using a deterministic rotation
 * based on the current Gregorian date. Same item shows for everyone all day.
 */
export function getTodayFeatured(date: Date = new Date()): InspirationItem {
  // Prefer holiday items if we're in their valid month.
  const month = date.getMonth() + 1;
  const inSeason = INSPIRATION_LIBRARY.filter(
    (i) => i.kind === 'holiday' && i.validMonth === month,
  );
  const pool = inSeason.length > 0 ? inSeason : INSPIRATION_LIBRARY;

  // Day-of-year based rotation
  const start = Date.UTC(date.getUTCFullYear(), 0, 0);
  const diff = Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()) - start;
  const dayOfYear = Math.floor(diff / 86_400_000);
  return pool[dayOfYear % pool.length];
}

