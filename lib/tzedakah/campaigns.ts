// ── Helpers ─────────────────────────────────────────────────────────────────
export function getCampaignBySlug(slug: string): TzedakahCampaign | null {
  return TZEDAKAH_CAMPAIGNS.find((c) => c.slug === slug) ?? null;
}

export function getActiveCampaigns(): TzedakahCampaign[] {
  return TZEDAKAH_CAMPAIGNS.filter((c) => c.active);
}

export function getCompletedCampaigns(): TzedakahCampaign[] {
  return TZEDAKAH_CAMPAIGNS.filter((c) => !c.active);
}

/** Активный сбор дня для блока на главной (ротация по дню). */
export function getTodayCampaign(date: Date = new Date()): TzedakahCampaign {
  const active = getActiveCampaigns();
  const pool = active.length > 0 ? active : TZEDAKAH_CAMPAIGNS;
  const start = Date.UTC(date.getUTCFullYear(), 0, 0);
  const diff = Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()) - start;
  const dayOfYear = Math.floor(diff / 86_400_000);
  return pool[dayOfYear % pool.length];
}

export function progressPercent(c: TzedakahCampaign): number | null {
  if (!c.goal) return null;
  return Math.min(100, Math.round((c.raised / c.goal) * 100));
}

export function formatUah(amount: number): string {
  return new Intl.NumberFormat('uk-UA', { maximumFractionDigits: 0 }).format(amount) + ' ₴';
}
